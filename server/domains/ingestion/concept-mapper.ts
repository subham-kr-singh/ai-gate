export interface ConceptMapping {
  subjectId: string;
  /** Subject.code, e.g. "OS" — recorded so a reviewer can verify the tag→subject step. */
  subjectCode: string;
  unitId: string;
  topicId: string;
  conceptIds: string[];
  /** 0..1 — the score of the winning match. */
  confidence: number;
  /** How the match was made, for the review UI. */
  matchedOn:
    | "section-title"
    | "chapter-title"
    | "tag"
    | "none"
    /** A model proposed the name and the deterministic matcher confirmed it
     * exists in the syllabus. Never treated as authoritative. */
    | "assisted-exact";
  /** Human-readable reason, shown to the reviewer. */
  rationale: string;
}

